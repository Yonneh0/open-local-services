    CHECK_EQ(oidWidth(tagId.format), SHA1_BYTES);
    LooseObject tagBack;
    CHECK(looseObjectReadAt(scratch, tagId, tagBack, error));
    CHECK(tagBack.kind == ObjectKind::Tag);
