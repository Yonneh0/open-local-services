    std::string path;
    CHECK(!looseObjectPath("", ObjectId(oids[0]), path));
    CHECK(path.empty());
    std::string err;
    LooseObject nowhere;
    CHECK(!looseObjectReadAt("", ObjectId(oids[0]), nowhere, err));
    CHECK(!err.empty());
