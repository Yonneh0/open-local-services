// The law an empty folder stands under, pinned at the byte layer. Git
// stores no folder that holds nothing: the empty folder is the empty tree
// — no bytes of content at all, under the known hash of nothing — and a
// tree holds exactly the entries it is handed. Nothing is dropped on the
// way from a caller's hands to the bytes, and no entry name reaches
// through a folder: a name ending at a '/' has no standing in a tree on
// either side of the serializer — refused with its words, never quietly
// left out. So the law "an empty folder is not a thing a commit carries"
// is not this layer's to keep in silence: nothing here drops a folder,
// and the save door is where it is said, before any byte is written.
TEST(an_empty_folder_is_the_empty_tree_and_a_tree_keeps_what_it_is_handed)
{
    std::string error;

    // What git stores for a folder with nothing in it: a tree of no
    // entries — the header and nothing past it — under the id every git
    // on the machine agrees the hash of nothing is.
    std::string raw;
    CHECK(objectBytes(ObjectKind::Tree, std::string(), raw, error));
    CHECK_EQ(raw, std::string("tree 0\0", 7));
    ObjectId emptyTree;
    CHECK(objectOid(raw, ObjectFormat::Sha1, emptyTree, error));
    CHECK_EQ(oidHex(emptyTree),
             std::string("4b825dc642cb6eb9a060e54bf8d69288fbee4904"));

    // A name that wears a path — a trailing '/' among them — stands in no
    // tree: the reader refuses it, and so does the writer. Not dropped:
    // refused, each with its words.
    TreeObject parsed;
    CHECK(!treeParse("40000 empty/" + std::string(20, '\0'), parsed, error));
    CHECK(!error.empty());
    TreeEntry worn;
    worn.mode = "40000";
    worn.name = "empty/";
    worn.id = emptyTree;
    TreeObject dressed;
    dressed.entries.push_back(worn);
    std::string bytes;
    CHECK(!treeSerialize(dressed, bytes, error));
    CHECK(!error.empty());

    // And a tree keeps, whole and in the order git keeps, every entry it
    // is handed — a directory entry included, even one whose tree is the
    // empty tree. A builder that drops nothing cannot be the place an
    // empty folder quietly disappears; the door speaks, and the bytes
    // that do get written are the entries the door agreed to.
    TreeEntry file;
    file.mode = "100644";
    file.name = "here.txt";
    file.id = emptyTree; // a claim of shape, not of content: any whole id stands
    TreeEntry holds;
    holds.mode = "40000";
    holds.name = "kept";
    holds.id = emptyTree;
    TreeObject built;
    built.entries.push_back(file); // "here.txt" before "kept/", the order git keeps
    built.entries.push_back(holds);
    std::string whole;
    CHECK(treeSerialize(built, whole, error));
    TreeObject again;
    CHECK(treeParse(whole, again, error));
    CHECK_EQ(again.entries.size(), 2u);
    if (again.entries.size() == 2u) {
        CHECK_EQ(again.entries[0].name, std::string("here.txt"));
        CHECK_EQ(again.entries[1].name, std::string("kept"));
        CHECK_EQ(again.entries[1].mode, std::string("40000"));
        CHECK_EQ(oidHex(again.entries[1].id), oidHex(emptyTree));
    }
    std::string roundAgain;
    CHECK(treeSerialize(again, roundAgain, error));
    CHECK_EQ(roundAgain, whole);
}
