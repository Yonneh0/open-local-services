// The hashes the whole layer is built on, at the answers every implementation of
// SHA-1 and SHA-256 states. Every fixture claim below leans on these, which is
// why the known answers are stated first and on their own.
TEST(object_hashes_answer_the_known_vectors)
{
    CHECK_EQ(sha1Hex(std::string()), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
    CHECK_EQ(sha1Hex("abc"), "a9993e364706816aba3e25717850c26c9cd0d89d");
    CHECK_EQ(sha1Hex("The quick brown fox jumps over the lazy dog"),
             "2fd4e1c67a2d28fced849ee1bb76e7391b93eb12");
    // The padding is where a message crosses a block, and at the two lengths
    // where the length field starts a block of its own.
    CHECK_EQ(sha1Hex(std::string(55, 'a')), "c1c8bbdc22796e28c0e15163d20899b65621d65a");
    CHECK_EQ(sha1Hex(std::string(56, 'a')), "c2db330f6083854c99d4b5bfb6e8f29f201be699");
    CHECK_EQ(sha1Hex(std::string(64, 'a')), "0098ba824b5c16427bd7a1122a5a442a25ec644d");
    CHECK_EQ(sha1Hex(std::string(65, 'a')), "11655326c708d70319be2610e8a57d9a5b959d3b");

    CHECK_EQ(sha256Hex(std::string()),
             "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
    CHECK_EQ(sha256Hex("abc"),
             "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
    CHECK_EQ(sha256Hex("The quick brown fox jumps over the lazy dog"),
             "d7a8fbb307d7809469ca9abcb0082e4f8d5651e46d3cdb762d02d0bf37c9e592");
    CHECK_EQ(sha256Hex(std::string(56, 'a')),
             "b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a");

    // The store behind an id is the wider one from the start: a sha1 id keeps
    // the bytes of its format and the rest stay zero, and an id of a length the
    // format does not ask for is refused rather than half-read.
    ObjectId small;
    std::string error;
    CHECK(oidParseHex("77626866b9dc450241b7ee8de07a25a327480109", ObjectFormat::Sha1, small,
                      error));
    CHECK_EQ(oidWidth(small.format), SHA1_BYTES);
    CHECK_EQ(oidRaw(small).size(), SHA1_BYTES);
    CHECK_EQ(oidHex(small), "77626866b9dc450241b7ee8de07a25a327480109");

    // The id is hex and nothing else, so the one call every layer of GitCore
    // uses - parse, to_hex, is_null - is the same name here for the same thing:
    // an id made from uppercase hex is held lowered, hex of the wider length is
    // the wider format, and the hex of zeros is the id of nothing.
    ObjectId named;
    CHECK(ObjectId::parse("A867EF798B215DB19EAF0C7B615C789792FE62B9", named));
    CHECK_EQ(named.to_hex(), "a867ef798b215db19eaf0c7b615c789792fe62b9");
    CHECK(named.valid());
    CHECK(!ObjectId::parse("nope", named));
    CHECK(ObjectId(std::string(40, '0')).is_null());
    CHECK(!named.is_null());
    CHECK(ObjectId::parse(std::string(64, '0'), named));
    CHECK_EQ(oidWidth(named.format), SHA256_BYTES);
    CHECK_EQ(oidRaw(named).size(), SHA256_BYTES);
    CHECK(named.is_null());
    CHECK(!oidParseHex("da39a3ee5e6b4b0d3255bfef95601890afd80709", ObjectFormat::Sha256, small,
                       error));
    CHECK(!error.empty());
    CHECK(!error.empty());
    CHECK(!objectOid("blob 0\0", ObjectFormat::Sha256, small, error));
    CHECK(!error.empty());
    CHECK(!oidParseHex("77626866b9dc450241b7ee8de07a25a32748010", ObjectFormat::Sha1, small,
                       error));
    CHECK(!error.empty());
    CHECK(!oidParseHex("g7626866b9dc450241b7ee8de07a25a327480109", ObjectFormat::Sha1, small,
                       error));
    CHECK(!error.empty());
}

// The header of an object, stated both ways. These are the refusals the reading
// of a loose file leans on, and each one keeps the reason it is going to answer
// with.
TEST(object_headers_are_read_and_refused)
{
    const std::string real = objectOf("blob 5", "hello");
    ObjectKind kind;
    std::uint64_t size;
    std::string error;
    CHECK(objectHeaderRead(real, kind, size, error));
    CHECK_EQ(std::string(kindName(kind)), "blob");
    CHECK_EQ(size, 5u);
    CHECK_EQ(objectHeaderMake(ObjectKind::Blob, 5ull), "blob 5" + std::string(1, '\0'));
    CHECK_EQ(objectHeaderMake(ObjectKind::Tree, 67ull), "tree 67" + std::string(1, '\0'));
    ObjectKind splitKind;
    std::uint64_t splitSize;
    std::string content;
    CHECK(objectSplit(real, splitKind, splitSize, content, error));
    CHECK_EQ(content, "hello");
    CHECK(error.empty());

    // A type word that is not one of the four git has.
    CHECK(!objectHeaderRead(objectOf("blb 5", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("Blob 5", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("blobk 5", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("pack 5", "hello"), kind, size, error));
    CHECK(!error.empty());

    // A size that is not the count of bytes behind the header.
    CHECK(!objectSplit(objectOf("blob 4", "hello"), splitKind, splitSize, content, error));
    CHECK(!error.empty());
    CHECK(!objectSplit(objectOf("blob 6", "hello"), splitKind, splitSize, content, error));
    CHECK(!error.empty());

    // A size that is not written the way git writes it.
    CHECK(!objectHeaderRead(objectOf("blob 05", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("blob -5", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("blob +5", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("blob ", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("blob 5 5", "hello"), kind, size, error));
    CHECK(!error.empty());
    CHECK(!objectHeaderRead(objectOf("blob 99999999999999999999999999999", "hello"), kind, size,
                            error));
    CHECK(!error.empty());
    // A header that never ends is not a header.
    CHECK(!objectHeaderRead("blob 5", kind, size, error));
    CHECK(!error.empty());
    // An empty object is an object, and its id is the one every git gives an
    // empty file.
    const std::string emptyBlob = objectOf("blob 0", "");
    CHECK(objectSplit(emptyBlob, splitKind, splitSize, content, error));
    CHECK_EQ(splitSize, 0u);
    CHECK(content.empty());
    ObjectId empty;
    CHECK(objectOid(emptyBlob, ObjectFormat::Sha1, empty, error));
    CHECK_EQ(oidHex(empty), "e69de29bb2d1d6434b8b29ae775ad8c2e48c5391");
    CHECK_EQ(sha1Hex(emptyBlob), "e69de29bb2d1d6434b8b29ae775ad8c2e48c5391");
}

// Every object of the fixture sample, read through the module, against what the
// manifest states git wrote: the id, the type word, the size, and the SHA-256 of
// the bytes the zlib wrapper carries. That the folder holds exactly the objects
// the manifest lists is a claim as well, so a fixture that was not recorded or
// an object that was not copied is caught here rather than left unasked.
TEST(the_fixture_objects_are_the_objects_git_wrote)
{
    const std::string manifestText = ols_test::read_fixture("loose-manifest.json");
    CHECK(!manifestText.empty());
    const std::vector<Listed> listed = listedObjects(manifestText);
    CHECK_EQ(listed.size(), 5u);
    CHECK_EQ(looseFilesUnder(fixtureObjectsDir()), listed.size());

    const std::string objectsDir = fixtureObjectsDir();
    std::size_t read = 0;
    for (const Listed &entry : listed)
    {
        const std::string name = "loose/" + entry.oid.substr(0, 2) + "/" + entry.oid.substr(2);
        CHECK(!ols_test::read_fixture(name).empty());

        ObjectId named;
        std::string error;
        CHECK(oidParseHex(entry.oid, ObjectFormat::Sha1, named, error));
        LooseObject value;
        // The path the id names is built by the module, and the bytes found
        // there are required to hash back to the id.
        CHECK(looseObjectReadAt(objectsDir, named, value, error));
        ++read;

        CHECK_EQ(oidHex(value.id), entry.oid);
        CHECK_EQ(std::string(kindName(value.kind)), entry.type);
        CHECK_EQ(value.size, entry.size);
        CHECK_EQ(value.content.size(), entry.size);
        // The header is the type word, a space, the size in digits, and a NUL.
        CHECK_EQ(value.raw.size(), entry.size + entry.type.size() +
                                      headerDigits(entry.size) + 2u);
        CHECK_EQ(value.raw.substr(0, entry.type.size()), entry.type);
        CHECK_EQ(sha256Hex(value.raw), entry.sha256);
        CHECK_EQ(sha1Hex(value.raw), entry.oid);

        // The size the header states is the size the stream inflates to, and a
        // smaller limit refuses without standing the whole of it.
        const std::string stream = ols_test::read_fixture(name);
        std::string limited;
        CHECK(inflateZlib(stream, value.raw.size(), limited, error));
        CHECK_EQ(limited, value.raw);
        CHECK(!inflateZlib(stream, value.raw.size() - 1ull, limited, error));
        CHECK(!error.empty());
    }
    CHECK_EQ(read, listed.size());
}

// The typed views of the fixture content: tree entries, a commit's people and
// their dates, a message. The values stated here are the ones oracle-commands.md
// records for the run that made these fixtures - the ls-tree lines, the commit
// header, the message - and the bytes come from the fixture. Re-serializing what
// was parsed writes back exactly those bytes, and those bytes hash to the id they
// are filed under.
TEST(the_object_model_reads_and_rewrites_the_fixture_bytes)
{
    const std::string objectsDir = fixtureObjectsDir();
    std::string error;

    auto rawOf = [&](const std::string &hex) {
        ObjectId named;
        if (!oidParseHex(hex, ObjectFormat::Sha1, named, error))
            return std::string();
        LooseObject value;
        if (!looseObjectReadAt(objectsDir, named, value, error))
            return std::string();
        return value.content;
    };

    // The root tree of the sample: a file and a directory. A directory is
    // "40000" in the bytes of a tree, without the leading zero an ls-tree line
    // shows - which is why the manifest states this tree at 67 bytes and not 68.
    const std::string rootTree = rawOf("d25250f5f7f874caffa476f3a69161b879d2cbc6");
    CHECK(!rootTree.empty());
    TreeObject root;
    CHECK(treeParse(rootTree, root, error));
    CHECK_EQ(root.entries.size(), 2u);
    CHECK_EQ(root.entries[0].mode, "100644");
    CHECK_EQ(root.entries[0].name, "a1.txt");
    CHECK_EQ(oidHex(root.entries[0].id), "e0396ffc6284bb3b460e027c49d05bbb31b273e1");
    CHECK_EQ(root.entries[1].mode, "40000");
    CHECK_EQ(root.entries[1].name, "nested");
    CHECK_EQ(oidHex(root.entries[1].id), "77626866b9dc450241b7ee8de07a25a327480109");
    CHECK(treeModeDirectory(root.entries[1].mode));
    CHECK(!treeModeValid("040000"));
    CHECK(!treeModeDirectory("100644"));

    std::string written;
    CHECK(treeSerialize(root, written, error));
    CHECK_EQ(written, rootTree);
    std::string whole;
    objectBytes(ObjectKind::Tree, written, whole, error);
    ObjectId again;
    CHECK(objectOid(whole, ObjectFormat::Sha1, again, error));
    CHECK_EQ(oidHex(again), "d25250f5f7f874caffa476f3a69161b879d2cbc6");

    // The tree below it: one file.
    const std::string innerTree = rawOf("77626866b9dc450241b7ee8de07a25a327480109");
    CHECK(!innerTree.empty());
    TreeObject inner;
    CHECK(treeParse(innerTree, inner, error));
    CHECK_EQ(inner.entries.size(), 1u);
    CHECK_EQ(inner.entries[0].mode, "100644");
    CHECK_EQ(inner.entries[0].name, "sub.txt");
    CHECK_EQ(oidHex(inner.entries[0].id), "f63ac6b34ade6c27cb84d19886049042a8bc2ce4");
    CHECK(treeSerialize(inner, written, error));
    CHECK_EQ(written, innerTree);

    // The commit: the tree it holds, no parents, and two people at the same
    // second, because the sample was made with the dates and the identity pinned.
    const std::string commitText = rawOf("a867ef798b215db19eaf0c7b615c789792fe62b9");
    CHECK(!commitText.empty());
    CommitObject commit;
    CHECK(commitParse(commitText, commit, error));
    CHECK_EQ(oidHex(commit.tree), "d25250f5f7f874caffa476f3a69161b879d2cbc6");
    CHECK(commit.parents.empty());
    CHECK(commit.headers.empty());
    CHECK_EQ(commit.author.name, "FixtureMaker");
    CHECK_EQ(commit.author.email, "fixture@example.com");
    CHECK_EQ(commit.author.seconds, 1704067200);
    CHECK_EQ(commit.author.zone, "+0000");
    CHECK_EQ(commit.committer.name, "FixtureMaker");
    CHECK_EQ(commit.committer.email, "fixture@example.com");
    CHECK_EQ(commit.committer.seconds, 1704067200);
    CHECK_EQ(commit.committer.zone, "+0000");
    CHECK_EQ(commit.message,
             "fixture objects: one commit, one tree with a subtree, two blobs\n");
    CHECK(commitSerialize(commit, written, error));
    CHECK_EQ(written, commitText);
    objectBytes(ObjectKind::Commit, written, whole, error);
    CHECK(objectOid(whole, ObjectFormat::Sha1, again, error));
    CHECK_EQ(oidHex(again), "a867ef798b215db19eaf0c7b615c789792fe62b9");

    // The blobs: content in, the id git filed it under out.
    const std::string a1 = rawOf("e0396ffc6284bb3b460e027c49d05bbb31b273e1");
    CHECK_EQ(a1, "alpha\nbravo\ncharlie\ndelta\necho\nfoxtrot\ngolf\nhotel\n");
    objectBytes(ObjectKind::Blob, a1, whole, error);
    CHECK(objectOid(whole, ObjectFormat::Sha1, again, error));
    CHECK_EQ(oidHex(again), "e0396ffc6284bb3b460e027c49d05bbb31b273e1");
    const std::string sub = rawOf("f63ac6b34ade6c27cb84d19886049042a8bc2ce4");
    CHECK_EQ(sub, "a smaller file below a directory, so the root tree holds a subtree\n");
    objectBytes(ObjectKind::Blob, sub, whole, error);
    CHECK(objectOid(whole, ObjectFormat::Sha1, again, error));
    CHECK_EQ(oidHex(again), "f63ac6b34ade6c27cb84d19886049042a8bc2ce4");

    // A commit the model will not take is not half-read: no blank line, and a
    // zone that is not a zone, are both refused with a reason.
    CommitObject broken;
    CHECK(!commitParse("tree d25250f5f7f874caffa476f3a69161b879d2cbc6\n", broken, error));
    CHECK(!error.empty());
    CHECK(!commitParse("tree d25250f5f7f874caffa476f3a69161b879d2cbc6\n"
                       "author FixtureMaker <fixture@example.com> 1704067200 +000\n"
                       "committer FixtureMaker <fixture@example.com> 1704067200 +0000\n"
                       "\n"
                       "a message\n",
                       broken, error));
    CHECK(!error.empty());
    CHECK(!commitParse("tree not-an-id\nauthor FixtureMaker <fixture@example.com> 1704067200 "
                       "+0000\ncommitter FixtureMaker <fixture@example.com> 1704067200 +0000\n"
                       "\n"
                       "a message\n",
                       broken, error));
    CHECK(!error.empty());
    // A stamp of more seconds than a number of any size holds: a hand-written
    // commit can say anything, and the count is refused at the count rather than
    // wrapped into a stamp that looks plausible and means something else.
    CHECK(!commitParse("tree d25250f5f7f874caffa476f3a69161b879d2cbc6\n"
                       "author FixtureMaker <fixture@example.com> 99999999999999999999999 +0000\n"
                       "committer FixtureMaker <fixture@example.com> 1704067200 +0000\n"
                       "\n"
                       "a message\n",
                       broken, error));
    CHECK(!error.empty());

    // A commit that carries headers the model does not name keeps them and
    // writes them back: a signed commit continues a header with a leading space,
    // and the bytes that come out are the bytes that went in.
    const std::string signedText = "tree d25250f5f7f874caffa476f3a69161b879d2cbc6\n"
                                   "parent a867ef798b215db19eaf0c7b615c789792fe62b9\n"
                                   "author FixtureMaker <fixture@example.com> 1704067200 +0000\n"
                                   "committer FixtureMaker <fixture@example.com> 1704067200 +0000\n"
                                   "gpgsig hello\n there\n"
                                   "\n"
                                   "a message\n";
    CommitObject carries;
    CHECK(commitParse(signedText, carries, error));
    CHECK_EQ(carries.parents.size(), 1u);
    CHECK_EQ(oidHex(carries.parents[0]), "a867ef798b215db19eaf0c7b615c789792fe62b9");
    CHECK_EQ(carries.headers.size(), 1u);
    CHECK_EQ(carries.headers[0].first, "gpgsig");
    CHECK_EQ(carries.headers[0].second, "hello\n there");
    std::string back;
    CHECK(commitSerialize(carries, back, error));
    CHECK_EQ(back, signedText);
}

// The order tree entries are kept in, and what breaks it. No fixture of this
// sample needs the rule, so this is stated of the format: a directory is
// compared as its name with a slash after it, so a file whose name continues a
// directory's sorts before that directory, because '.' (0x2e) is below '/'
// (0x2f).
TEST(tree_entries_are_kept_in_the_order_git_keeps_them)
{
    std::string error;
    ObjectId file;
    ObjectId directory;
    CHECK(oidParseHex("e0396ffc6284bb3b460e027c49d05bbb31b273e1", ObjectFormat::Sha1, file,
                      error));
    CHECK(oidParseHex("77626866b9dc450241b7ee8de07a25a327480109", ObjectFormat::Sha1,
                      directory, error));

    const TreeEntry continues{"100644", "nested.txt", file};
    const TreeEntry named{"40000", "nested", directory};
    const TreeEntry alsoFile{"100644", "a1.txt", file};
    const TreeEntry longerName{"100644", "nested.txt.x", file};
    CHECK_EQ(treeEntryCompare(continues, named), -1);
    CHECK_EQ(treeEntryCompare(named, continues), 1);
    CHECK_EQ(treeEntryCompare(alsoFile, named), -1);
    CHECK_EQ(treeEntryCompare(continues, longerName), -1);
    CHECK_EQ(treeEntryCompare(named, named), 0);

    // The bytes of a tree in the order that holds, and in the order that does
    // not.
    auto bytesOf = [&](const TreeEntry &entry) {
        std::string out = entry.mode;
        out += ' ';
        out += entry.name;
        out += std::string(1, '\0');
        out += oidRaw(entry.id);
        return out;
    };
    const std::string keptBytes = bytesOf(continues) + bytesOf(named);
    const std::string brokenBytes = bytesOf(named) + bytesOf(continues);
    TreeObject none;
    CHECK(treeParse(keptBytes, none, error));
    CHECK_EQ(none.entries.size(), 2u);
    std::string sameOrder;
    CHECK(treeSerialize(none, sameOrder, error));
    CHECK_EQ(sameOrder, keptBytes);
    CHECK(!treeParse(brokenBytes, none, error));
    CHECK(!error.empty());

    // What else a tree cannot carry: a mode of a form a tree never holds, a
    // name that reaches through folders, a name given twice, an id that is not
    // an id.
    CHECK(!treeParse("040000 nested" + std::string(20, '\0'), none, error));
    CHECK(!error.empty());
    CHECK(!treeParse("100644 nested/sub.txt" + std::string(20, '\0'), none, error));
    CHECK(!error.empty());
    CHECK(!treeParse("100644 a1.txt" + std::string(20, '\0') + "100644 a1.txt" +
                          std::string(20, '\0'),
                      none, error));
    CHECK(!error.empty());
    CHECK(!treeParse("100644 a1.txt" + std::string(19, '\0'), none, error));
    CHECK(!error.empty());
    CHECK(!treeParse("100644 a1.txt" + std::string(20, 'g'), none, error));
    CHECK(!error.empty());
    // An empty tree is a tree, and it is written as nothing at all.
    CHECK(treeParse(std::string(), none, error));
    CHECK(none.entries.empty());
    std::string written;
    CHECK(treeSerialize(none, written, error));
    CHECK(written.empty());
}

// A loose object written where it does not stand yet: the file comes with the
// two-digit folder it needs, carries the object behind a wrapper of stored
// blocks, and is named for the hash of its bytes - the id the fixtures name it
