// tests/gitcore/test_objects.cpp — the object layer of GitCore, Phase B1.
//
// The ground of these claims is git.exe: fixtures/loose holds every loose object
// git wrote for the sample described in oracle-commands.md, and loose-manifest.json
// states each one's oid, type, size, and the SHA-256 of the raw bytes behind its
// zlib wrapper. A case reads those files, asks the module to read them again, and
// states what the two agree on. Where a claim can only be made about the format
// itself - a fixed-Huffman block, the order tree entries stand in, a header that
// says something impossible - the case says that plainly and states the format.
//
// The module is pulled in rather than compiled beside it, the same way the
// harness pulls in a case: one include, and the target asks nothing of
// CMakeLists for it.
