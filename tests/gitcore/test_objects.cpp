// One line of loose-manifest.json. The file is read rather than carried here so
// that a fixture regenerated by git moves these claims with it; the reader is a
// scan for the names this layer needs, and the manifest's own prose is not
// parsed at all - it is a description, and it carries quotes of its own.
struct Listed
{
    std::string oid;
    std::string type;
    std::string sha256;
    std::uint64_t size{0};
};

std::string fieldValue(const std::string &body, const std::string &name)
{
    const std::string key = "\"" + name + "\"";
    const std::size_t at = body.find(key);
    if (at == std::string::npos)
        return std::string();
    std::size_t cursor = body.find(':', at + key.size());
    if (cursor == std::string::npos)
        return std::string();
    ++cursor;
    while (cursor < body.size() && (body[cursor] == ' ' || body[cursor] == '\t' ||
                                    body[cursor] == '\n'))
        ++cursor;
    if (cursor < body.size() && body[cursor] == '"')
    {
        const std::size_t end = body.find('"', cursor + 1);
        if (end == std::string::npos)
            return std::string();
        return body.substr(cursor + 1, end - cursor - 1);
    }
    std::size_t stop = body.find_first_of(",\n}", cursor);
    if (stop == std::string::npos)
        stop = body.size();
    while (stop > cursor && (body[stop - 1] == ' ' || body[stop - 1] == '\t'))
        --stop;
    return body.substr(cursor, stop - cursor);
}

std::uint64_t countedFrom(const std::string &digits)
{
    std::uint64_t counted = 0;
    for (const char c : digits)
    {
        if (c < '0' || c > '9')
            return 0;
        counted = counted * 10ull + static_cast<std::uint64_t>(c - '0');
    }
    return counted;
}

std::vector<Listed> listedObjects(const std::string &manifest)
{
    std::vector<Listed> found;
    const std::size_t marker = manifest.find("\"objects\"");
    if (marker == std::string::npos)
        return found;
    std::size_t cursor = manifest.find('[', marker);
    if (cursor == std::string::npos)
        return found;
    for (;;)
    {
        const std::size_t open = manifest.find('{', cursor + 1);
        if (open == std::string::npos)
            return found;
        const std::size_t close = manifest.find('}', open + 1);
        if (close == std::string::npos)
            return found;
        const std::string body = manifest.substr(open + 1, close - open - 1);
        Listed entry;
        entry.oid = fieldValue(body, "oid");
        entry.type = fieldValue(body, "type");
        entry.sha256 = fieldValue(body, "content_sha256");
        entry.size = countedFrom(fieldValue(body, "size"));
        if (!entry.oid.empty())
            found.push_back(entry);
        cursor = close;
    }
}

// How many digits a count is written as: the header of an object states it, and
// the header is what stands before the content.
std::size_t headerDigits(std::uint64_t size)
{
    std::size_t digits = 0;
    for (std::uint64_t value = size; value > 0ull; value /= 10ull)
        ++digits;
    return digits == 0ull ? 1ull : digits;
}

// The objects/ folder of the fixture sample, beside this folder.
std::string fixtureObjectsDir() { return ols_test::fixtures_root + "/loose"; }

// Every regular file under the two-digit folders of an objects/ folder.
std::size_t looseFilesUnder(const std::string &dir)
{
    std::size_t found = 0;
    std::error_code outer{};
    for (std::filesystem::directory_iterator folder(dir, outer);
         !outer && folder != std::filesystem::directory_iterator(); ++folder)
    {
        std::error_code innerAsked{};
        for (std::filesystem::directory_iterator inner(folder->path(), innerAsked);
             !innerAsked && inner != std::filesystem::directory_iterator(); ++inner)
        {
            std::error_code regular{};
            if (std::filesystem::is_regular_file(inner->path(), regular))
                ++found;
        }
    }
    return outer ? 0u : found;
}

// A folder of the scratch of this machine, named for this run and left as it
// came. The objects these cases write are the objects git wrote, so a folder
// that kept an earlier run's copy would answer for its own work rather than
// for this run's.
std::string scratchDir(const std::string &name)
{
    std::error_code here{};
    std::filesystem::path base = std::filesystem::temp_directory_path(here);
    if (here || base.empty())
        return std::string();
    std::ostringstream where;
    where << "ols-b1-" << name << "-" << std::chrono::steady_clock::now().time_since_epoch().count();
    base /= where.str();
    std::error_code made{};
    std::filesystem::create_directories(base, made);
    if (made)
        return std::string();
    return base.string();
}

bool scratchGone(const std::string &path)
{
    std::error_code removed{};
    std::filesystem::remove_all(path, removed);
    if (removed)
        return false;
    std::error_code asked{};
    return !std::filesystem::exists(path, asked);
}

// An object's bytes, written out where a C++ literal would drop the NUL that
// ends a header.
std::string objectOf(const std::string &header, const std::string &content)
{
    return header + std::string(1, '\0') + content;
}

